'use strict';
const assert = require('node:assert/strict');
const { flattenStroke, roleAt, splitByColor, frameFor, slotFor, mapPoint, median } = require('../src/vector-strokes');
const { transform, pathBox } = require('../src/hangul');
const { topology } = require('../src/topology');
const { validStrokes } = require('../src/vector-correction');
const line = flattenStroke([[.1,.5],[.9,.5]],100);
assert.deepEqual(line[0],[10,50]); assert.deepEqual(line.at(-1),[90,50]);
assert(line.length > 100 && line.every((p)=>Math.abs(p[1]-50)<1e-6));
const curve = flattenStroke([[0,0],[.5,1],[1,0]],100,0.1);
assert.deepEqual(curve[0],[0,0]); assert.deepEqual(curve.at(-1),[100,0]);
assert(curve.some(p=>Math.abs(p[0]-43.75)<0.15 && Math.abs(p[1]-62.5)<0.15),'replays the same quadratic smoothing as the writing pad');
const size=100, L=new Uint8Array(size*size), V=new Uint8Array(size*size);
for(let y=48;y<=52;y++) for(let x=10;x<=90;x++) (x<50?L:V)[y*size+x]=1;
const masks={L,V};
assert.equal(roleAt([20,50],masks,size,['L','V']).role,'L');
assert.equal(roleAt([70,50],masks,size,['L','V']).role,'V');
const split=splitByColor([{points:[[.1,.5],[.9,.5]]}],masks,size,['L','V']);
assert.equal(split.missing,0); assert.equal(split.byRole.L.length,1); assert.equal(split.byRole.V.length,1);
assert(Math.abs(split.byRole.L[0].at(-1)[0] - split.byRole.V[0][0][0]) < 1e-8,'a single stroke can split at the manually painted boundary');
assert.throws(()=>splitByColor([{points:[[.1,.5],[.9,.5]]}],masks,size,['L','V'],10),/너무 복잡/,'sampling has a finite budget');
assert.equal(validStrokes([{points:[[.1,.1],[1.01,.2]]}]),null,'malformed coordinates cannot be silently clamped');
assert.equal(validStrokes(Array.from({length:1001},()=>({points:[[.5,.5]]}))),null,'excessive stroke counts fall back');
assert.deepEqual(validStrokes([{points:[[.1,.2],[.8,.9]]}]),[{points:[[.1,.2],[.8,.9]]}]);
const onlyV=splitByColor([{points:[[.1,.5],[.9,.5]]}],{L:new Uint8Array(size*size),V:Uint8Array.from(L,(v,i)=>v||V[i]?1:0)},size,['L','V']);
assert.equal(onlyV.byRole.L.length,0,'do not guess a role from where ink was drawn');
assert.equal(onlyV.byRole.V.length,1);
const blank=splitByColor([{points:[[.1,.5],[.9,.5]]}],{L:new Uint8Array(size*size)},size,['L']);
assert(blank.missing>0 && !blank.byRole.L.length,'uncolored ink is not silently assigned');
const frame=frameFor({x0:20,y0:10,x1:119,y1:209},{inset:90});
assert(Math.abs(frame.scale-4.1)<1e-8);
assert.deepEqual(mapPoint([20,10],frame),[295,910]);
const d='M100 200L500 200L500 800L100 800Z', slot={x:65,y:60,sx:.46,sy:.56};
const fit=slotFor(d,slot), box=pathBox(transform(d,slot,false));
assert(Math.abs(box.x0-(100*fit.kx+fit.tx))<.2 && Math.abs(box.x1-(500*fit.kx+fit.tx))<.2);
assert(Math.abs(box.y0-(200*fit.ky+fit.ty))<.2 && Math.abs(box.y1-(800*fit.ky+fit.ty))<.2);
assert.equal(median([4,1,8,3]),3.5);
const ring=new Uint8Array(31*31);for(let y=5;y<=25;y++)for(let x=5;x<=25;x++)if(x<=8||x>=22||y<=8||y>=22)ring[y*31+x]=1;
assert.deepEqual(topology(ring,31,31),{components:1,holes:1});
console.log('vector trajectories, manual color split, slot transforms and contour warnings passed');
